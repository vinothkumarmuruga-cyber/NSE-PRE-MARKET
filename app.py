    "        rows.append({\n",
    "            \"Symbol\": symbol,\n",
    "            \"Pre Open\": pre_open_price,\n",
    "            \"Prev Close\": row[\"Prev Close\"],\n",
    "            \"% Change\": row[\"% Change\"],\n",
