    "def get_previous_levels(equity_key):\n",
    "    hist = fetch_upstox_history(equity_key)\n",
    "\n",
    "    if hist.empty:\n",
    "        return None\n",
    "\n",
    "    prev_day = hist.iloc[-1]\n",
