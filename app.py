    "# ---------------------------------------------------------------------\n",
    "# Top 5 gainers / losers with CE / PE strikes\n",
    "# ---------------------------------------------------------------------\n",
    "def get_top5_premarket_with_strikes(options):\n",
    "    preopen = fetch_nse_preopen_fo()\n",
    "\n",
    "    if preopen.empty:\n",
    "        print(\"No NSE pre-open data received.\")\n",
    "        return pd.DataFrame(), pd.DataFrame()\n",
