    "# ---------------------------------------------------------------------\n",
    "# Add prev D/W/M levels + CE/PE prev close + straddle breakeven levels\n",
    "# ---------------------------------------------------------------------\n",
    "def add_levels_and_bep(df, equities, options, side):\n",
    "    rows = []\n",
    "\n",
    "    for _, row in df.iterrows():\n",
    "        symbol = row[\"Symbol\"]\n",
