    "        \"Pre Day Low\": prev_day[\"low\"],\n",
    "        \"Pre Week Low\": prev_week[\"low\"].min(),\n",
    "        \"Pre Month Low\": prev_month[\"low\"].min(),\n",
    "    }\n",
    "\n",
    "\n",
    "def get_prev_close(instrument_key):\n",
    "    if instrument_key is None:\n",
